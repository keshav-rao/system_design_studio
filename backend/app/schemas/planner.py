"""Pydantic v2 schemas for planning, requirements interview, and proposals.

These schemas interface between the LangGraph workflow, the LLM generator
(DeepSeek-R1-Distill-Qwen-32B), the catalog, and the deterministic validator.
"""

import uuid
from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.validator import (
    DesignDocument,
    DesignEdge,
    DesignNode,
    DesignRequirements,
    ValidationIssue,
)


class EvidenceLink(BaseModel):
    """Grounding citation from the RAG knowledge base."""

    model_config = ConfigDict(extra="ignore")

    source_id: str | None = Field(
        default=None, description="UUID string of source document if known"
    )
    source_title: str = Field(..., description="Title of the cited reference")
    collection: str = Field(..., description="Knowledge base collection name")
    section_path: str | None = Field(
        default=None, description="Heading breadcrumbs (e.g. # Caching > ## Redis)"
    )
    snippet: str = Field(..., description="Excerpt supporting the decision")
    relevance_score: float = Field(
        default=0.0, description="Rerank or retrieval score"
    )


class AlternativeConsidered(BaseModel):
    """Component or pattern considered and why it was chosen or rejected."""

    model_config = ConfigDict(extra="ignore")

    component_slug: str = Field(
        ..., description="Catalog slug of the chosen or alternative component"
    )
    considered_against: str = Field(
        ..., description="Alternative that was compared against"
    )
    rationale: str = Field(
        ..., description="Architectural reasoning for the selection"
    )


class ArchitectureProposal(BaseModel):
    """Structured proposal generated by DeepSeek-R1 / LangGraph planner."""

    model_config = ConfigDict(extra="ignore")

    title: str = Field(
        ..., description="Short architecture title (e.g. Tinder Matching Engine)"
    )
    summary: str = Field(
        ..., description="Comprehensive architecture overview and data flow"
    )

    nodes: list[DesignNode] = Field(
        ..., min_length=1, description="Catalog-grounded system components"
    )
    edges: list[DesignEdge] = Field(
        default_factory=list, description="Connections between components"
    )
    requirements: DesignRequirements = Field(
        default_factory=DesignRequirements,
        description="Non-functional requirements satisfied",
    )
    assumptions: list[str] = Field(
        default_factory=list,
        description="Assumptions made about traffic, data size, or operations",
    )
    evidence_links: list[EvidenceLink] = Field(
        default_factory=list,
        description="Citations from knowledge base supporting this design",
    )
    alternatives_considered: list[AlternativeConsidered] = Field(
        default_factory=list,
        description="Tradeoffs and alternatives evaluated",
    )

    def as_design_document(self) -> DesignDocument:
        """Convert to standard DesignDocument for deterministic validation."""
        return DesignDocument(
            nodes=self.nodes,
            edges=self.edges,
            requirements=self.requirements,
        )


# ---------------------------------------------------------------------------
# Requirements Interview Schemas
# ---------------------------------------------------------------------------


class InterviewQuestion(BaseModel):
    """A single requirement interview question."""

    id: str = Field(..., description="Unique question identifier")
    question: str = Field(..., description="User-facing prompt")
    category: str = Field(
        ...,
        description="Category: scale, traffic, latency, durability, regions, domain",
    )
    options: list[str] = Field(
        default_factory=list, description="Preset choices if multiple choice"
    )
    default_value: Any | None = Field(
        default=None, description="Suggested or default answer"
    )
    explanation: str | None = Field(
        default=None, description="Why this requirement matters architecturally"
    )


class InterviewAnswer(BaseModel):
    """Answer provided for a question."""

    question_id: str = Field(..., description="Matches InterviewQuestion.id")
    answer: Any = Field(..., description="User answer value")


class InterviewRequest(BaseModel):
    """Request to begin or continue an interview."""

    app_description: str = Field(
        ..., min_length=5, description="High-level application idea"
    )
    answers: list[InterviewAnswer] = Field(
        default_factory=list, description="Answers collected so far"
    )


class InterviewResponse(BaseModel):
    """Result of an interview step."""

    app_description: str = Field(..., description="Target application")
    completed: bool = Field(
        ..., description="True if sufficient requirements gathered to plan"
    )
    questions: list[InterviewQuestion] = Field(
        default_factory=list, description="Current or remaining questions"
    )
    inferred_requirements: DesignRequirements = Field(
        default_factory=DesignRequirements,
        description="Calculated non-functional requirements",
    )


# ---------------------------------------------------------------------------
# Project & Design REST Schemas
# ---------------------------------------------------------------------------


class ProjectCreate(BaseModel):
    """Payload to create a new project."""

    name: str = Field(..., min_length=2, max_length=255)
    description: str | None = Field(default=None)


class ProjectResponse(BaseModel):
    """Project metadata."""

    id: uuid.UUID
    name: str
    description: str | None = None
    created_at: datetime
    updated_at: datetime
    versions_count: int = 0


class PlanRequest(BaseModel):
    """Request to generate an architecture plan for a project."""

    app_description: str = Field(
        ..., min_length=5, description="Application description or requirements"
    )
    requirements: DesignRequirements | None = Field(
        default=None, description="Explicit NFRs if already finalized"
    )
    interview_answers: list[InterviewAnswer] = Field(
        default_factory=list, description="Collected interview answers"
    )


class DesignVersionResponse(BaseModel):
    """A full design proposal version."""

    id: uuid.UUID
    project_id: uuid.UUID
    version_number: int
    title: str
    summary: str
    requirements: DesignRequirements
    nodes: list[DesignNode]
    edges: list[DesignEdge]
    assumptions: list[str]
    evidence_links: list[EvidenceLink]
    alternatives_considered: list[AlternativeConsidered]
    validation_issues: list[ValidationIssue]
    is_valid: bool
    created_at: datetime
